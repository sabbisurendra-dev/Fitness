export function searchFoodsCatalog(query: string): FoodDatabaseItem[] {
  const cleaned = query.trim().toLowerCase();
  if (!cleaned) {
    // Return diverse top Indian + Global staples when search bar is empty
    const featuredIds = [
      "food-grilled-chicken-breast",
      "food-salmon-fillet",
      "food-chapati-roti",
      "food-dal-tadka",
      "food-paneer-raw",
      "food-whole-boiled-egg",
      "food-steamed-basmati-rice",
      "food-indian-dahi-curd",
      "food-idli",
      "food-rolled-oats-dry",
      "food-whey-protein-isolate",
      "food-drinking-water",
    ];
    return FOOD_DATABASE.filter((f) => featuredIds.includes(f.id));
  }

  const tokens = cleaned.split(/\s+/).filter(Boolean);
  const scored = FOOD_DATABASE.map((item) => {
    const haystack = [item.name, item.category, ...item.aliases]
      .join(" ")
      .toLowerCase();
    const nameLower = item.name.toLowerCase();
    let score = 0;

    if (nameLower === cleaned) score += 100;
    else if (nameLower.startsWith(cleaned)) score += 60;
    else if (nameLower.includes(cleaned)) score += 40;

    let allMatch = true;
    for (const token of tokens) {
      if (haystack.includes(token)) {
        score += nameLower.includes(token) ? 15 : 8;
      } else {
        allMatch = false;
      }
    }

    if (!allMatch) score = 0;
    return { item, score };
  })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((entry) => entry.item);

  return scored;
}

export function calculateFoodPortionNutrition(
  food: FoodDatabaseItem,
  weightGrams: number,
  quantity = 1
): {
  totalGrams: number;
  calories: number;
  protein: number;
  carbs: number;
  fats: number;
  fiberGrams: number;
  waterLiters: number;
} {
  const safeGrams = Math.max(0, Number(weightGrams) || 0);
  const safeQty = Math.max(0.1, Number(quantity) || 1);
  const totalGrams = Math.round(safeGrams * safeQty);
  const scale = totalGrams / 100;

  return {
    totalGrams,
    calories: Math.round(food.caloriesPer100g * scale),
    protein: Number((food.proteinPer100g * scale).toFixed(1)),
    carbs: Number((food.carbsPer100g * scale).toFixed(1)),
    fats: Number((food.fatsPer100g * scale).toFixed(1)),
    fiberGrams: Number((food.fiberPer100g * scale).toFixed(1)),
    waterLiters: Number((food.waterLitersPer100g * scale).toFixed(2)),
  };
}
